import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';

/*
  Генератор слоёв музыкального узора. Запуск из корня темы:  node scripts/build-deco.mjs

  Картинки собираются скриптом, а не режутся руками, потому что их числа —
  координаты нот, радиусы колец, цвета точек — это КОПИЯ данных сайта. Копию,
  сделанную руками, нечем сверить с источником, когда источник поменяется.
*/
const OUT = fileURLToPath(new URL('../assets/', import.meta.url));

/*
  Данные скопированы ОДИН В ОДИН из
  apps/web/src/features/editor/components/renderer/decorative/DecorativeBackground.tsx
  (тип `music-glyphs`) — чтобы узор на форуме совпал с узором сайта, а не был на
  него похож.
*/

// [left%, top%, размер px, — , —] ; две последние величины на сайте задают
// анимацию, здесь слой статический и они не нужны.
const GLYPH_FIELD = [
  [6, 18, 40], [16, 64, 26], [24, 33, 34],
  [33, 78, 22], [42, 14, 30], [50, 52, 44],
  [58, 28, 24], [66, 70, 36], [74, 20, 28],
  [82, 58, 38], [90, 36, 24], [12, 88, 30],
  [48, 84, 26], [88, 80, 34],
];

/*
  ⚠️ Из набора убран U+1D11E (скрипичный ключ). На сайте он рисуется шрифтом
  'Noto Music' с фолбэком, а внутри фоновой картинки чужие шрифты не грузятся:
  на машине без нотного шрифта вместо ключа встал бы квадрат — и не мелкий, а в
  180 px. Остальные пять знаков есть в любом системном шрифте.
*/
const GLYPHS = ['♪', '♫', '♬', '♭', '♯'];

// Цветные точки орбитальных колец (viewBox 200×200, центр 100,100): [cx, cy, r, hsl]
const ORBIT_DOTS = [
  [100, 16, 3.2, '189 80% 50%'],
  [172, 142, 2.8, '38 92% 55%'],
  [46, 131, 2.6, '142 60% 48%'],
  [135, 80, 2.4, '330 70% 60%'],
  [60, 62, 2.6, '220 80% 62%'],
  [156, 56, 2.4, '48 95% 55%'],
];

/*
  ⚠️ Поле нот — ПОВТОРЯЮЩИЙСЯ модуль, а не одна картинка на весь блок.

  Первая редакция была одной картинкой 1200×500 с `mask-size: cover`. Проверка
  рендером показала: на нашей полосе (примерно 1900×420, то есть 4,5:1 против
  2,4:1 у картинки) `cover` обрезает поле по высоте, и из четырнадцати нот
  остаются ТРИ. Растянуть картинку вместо обрезки нельзя — ноты раздавило бы
  вдвое по горизонтали.

  Модуль 600×300 с постоянным размером знаков решает и то, и другое: плотность
  одинакова при любой ширине блока, а размеры нот заданы в пикселях — ровно как
  на сайте, где у каждого знака свой font-size.
*/
const W = 600;
const H = 300;
const зажать = (v, min, max) => Math.min(max, Math.max(min, v));
const glyphs = GLYPH_FIELD.filter((_, i) => i % 2 === 0).map(([l, t, fs], i) => {
  const x = зажать((l / 100) * W, 46, W - 46).toFixed(1);
  const y = зажать((t / 100) * H, 44, H - 26).toFixed(1);
  return `<text x="${x}" y="${y}" font-size="${fs}" fill="#000" opacity="0.62">${GLYPHS[i % GLYPHS.length]}</text>`;
}).join('\n  ');

const svgGlyphs = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" font-family="Georgia, 'Segoe UI Symbol', serif">
  ${glyphs}
</svg>
`;

/*
  Орбитальные кольца — только штрихи, без цветных точек: этот файл тоже идёт
  маской. Прозрачность колец 0.32 взята с сайта и запечена сюда, потому что у
  маски работает АЛЬФА, а не цвет.
*/
const svgOrbit = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200">
  <g fill="none" stroke="#000" stroke-width="0.7" opacity="0.32">
    <circle cx="100" cy="100" r="40"/>
    <circle cx="100" cy="100" r="62"/>
    <circle cx="100" cy="100" r="84"/>
  </g>
</svg>
`;

/*
  Цветные точки на тех же орбитах — ОТДЕЛЬНЫМ файлом и обычной картинкой, а не
  маской: маска берёт альфу и цвет бы потеряла, а эти шесть точек и есть
  единственное цветное пятно узора. Цвета насыщенные и читаются на обеих схемах.
*/
const dots = ORBIT_DOTS.map(([cx, cy, r, c]) => `<circle cx="${cx}" cy="${cy}" r="${r}" fill="hsl(${c})"/>`).join('\n  ');
const svgDots = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200">
  ${dots}
</svg>
`;

const files = {
  'tt-glyphs.svg': svgGlyphs,
  'tt-orbit.svg': svgOrbit,
  'tt-orbit-dots.svg': svgDots,
};

for (const [name, body] of Object.entries(files)) {
  writeFileSync(`${OUT}/${name}`, body, 'utf8');
  console.log(`  ${name.padEnd(20)} ${body.length} Б`);
}

console.log('\n=== контроль ===');
console.log('  знаков в модуле:', (svgGlyphs.match(/<text /g) || []).length, '(ожидаем 7)');
console.log('  колец:', (svgOrbit.match(/<circle /g) || []).length, '(ожидаем 3)');
console.log('  цветных точек:', (svgDots.match(/<circle /g) || []).length, '(ожидаем 6)');
console.log('  ключа U+1D11E нет:', !svgGlyphs.includes('\u{1D11E}'));
